/** Primary MCC for an ISO country code, or '' when unknown. */
export function mccForIso(iso: string): string {
  return ISO_TO_MCC[iso.toUpperCase()]?.[0] ?? '';
}

/** All MCCs for an ISO country code (multi-MCC countries like IN/US). */
export function mccsForIso(iso: string): string[] {
  return ISO_TO_MCC[iso.toUpperCase()] ?? [];
}
